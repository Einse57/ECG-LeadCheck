"""Turn study/results.json into study/RESULTS.md and study/false_mi.png."""
import json
import pathlib

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402

ROOT = pathlib.Path(__file__).resolve().parents[1]
r = json.load(open(ROOT / "study/results.json"))
ORDER = ["LA/RA", "LA/LL", "RA/LL", "rotation RA>LA>LL", "rotation RA>LL>LA", "RA/RL", "LA/RL",
         "V1/V2", "V2/V3", "V3/V4", "V4/V5", "V5/V6"]
GROUPS = {"standard (4 models)": [k for k, m in r["models"].items() if not m["swap_aug"]],
          "swap-augmented (2 models)": [k for k, m in r["models"].items() if m["swap_aug"]]}


def rng(vals):
    vals = [v for v in vals if v is not None and not np.isnan(v)]
    return f"{100 * min(vals):.1f}-{100 * max(vals):.1f}" if vals else "n/a"


lines = ["# Results: electrode interchanges vs ECG diagnosis models", "",
         "Generated by `scripts/study_report.py` from `study/results.json`. PTB-XL fold 10; every interchange is "
         "applied to every recording. Ranges are min-max across models.", ""]
std = GROUPS["standard (4 models)"]
aug = GROUPS["swap-augmented (2 models)"]
lines += ["| model | clean macro-AUROC |", "|---|---|"]
lines += [f"| {k} | {r['models'][k]['clean_macro_auroc']:.4f} |" for k in r["models"]]
lines += ["", "## Standard models: no protection vs LeadCheck detect-and-correct", "",
          "| interchange | diagnosis changed | false MI on normal ECGs | missed MI | macro-AUROC | changed, with LeadCheck | false MI, with LeadCheck | sent to re-record |",
          "|---|---|---|---|---|---|---|---|"]
for k in ORDER:
    none = [r["models"][m]["none"][k] for m in std]
    dc = [r["models"][m]["detect_correct"][k] for m in std]
    rr = dc[0]["rerecord"]
    approx = rr > 0.5
    lines.append(f"| {k} | {rng([x['flip'] for x in none])} % | {rng([x['false_mi'] for x in none])} % | "
                 f"{rng([x['missed_mi'] for x in none])} % | {min(x['macro_auroc'] for x in none):.3f}-{max(x['macro_auroc'] for x in none):.3f} | "
                 f"{'n/a' if approx else rng([x['flip'] for x in dc]) + ' %'} | {'n/a' if approx else rng([x['false_mi'] for x in dc]) + ' %'} | {100 * rr:.1f} % |")
lines += ["", "Cost on correctly recorded ECGs (detect-and-correct applied to the unmodified recording): diagnosis changed "
          f"{rng([r['models'][m]['detect_correct_clean_cost']['flip'] for m in std])} %, "
          f"macro-AUROC change {min(r['models'][m]['detect_correct_clean_cost']['macro_auroc'] - r['models'][m]['clean_macro_auroc'] for m in std):+.4f} to "
          f"{max(r['models'][m]['detect_correct_clean_cost']['macro_auroc'] - r['models'][m]['clean_macro_auroc'] for m in std):+.4f}. "
          f"LeadCheck flags {100 * r['leadcheck']['clean_flagged']:.1f} % of correct ECGs.", "",
          "## Swap-augmented training (no LeadCheck)", "",
          "| interchange | diagnosis changed | false MI on normal ECGs | missed MI | macro-AUROC |", "|---|---|---|---|---|"]
for k in ORDER:
    none = [r["models"][m]["none"][k] for m in aug]
    lines.append(f"| {k} | {rng([x['flip'] for x in none])} % | {rng([x['false_mi'] for x in none])} % | {rng([x['missed_mi'] for x in none])} % | "
                 f"{min(x['macro_auroc'] for x in none):.3f}-{max(x['macro_auroc'] for x in none):.3f} |")
(ROOT / "study/RESULTS.md").write_text("\n".join(lines) + "\n")

fig, ax = plt.subplots(figsize=(10, 4.2))
x = np.arange(len(ORDER))
w = 0.27
series = [("standard model", [np.mean([r["models"][m]["none"][k]["false_mi"] for m in std]) for k in ORDER], "#c0392b"),
          ("swap-augmented model", [np.mean([r["models"][m]["none"][k]["false_mi"] for m in aug]) for k in ORDER], "#e8a33d"),
          ("standard + LeadCheck", [np.nanmean([r["models"][m]["detect_correct"][k]["false_mi"] for m in std])
                                     if r["models"][std[0]]["detect_correct"][k]["rerecord"] < 0.5 else 0 for k in ORDER], "#2e86de")]
for i, (label, vals, col) in enumerate(series):
    ax.bar(x + (i - 1) * w, 100 * np.array(vals), w, label=label, color=col)
for i, k in enumerate(ORDER):
    if r["models"][std[0]]["detect_correct"][k]["rerecord"] > 0.5:
        ax.text(x[i] + w, 2, "re-record", rotation=90, ha="center", va="bottom", fontsize=7, color="#2e86de")
ax.set_xticks(x)
ax.set_xticklabels([k.replace("rotation ", "rot ") for k in ORDER], rotation=35, ha="right", fontsize=9)
ax.set_ylabel("normal ECGs called MI (%)")
ax.set_title("Swapped electrodes make ECG-AI see heart attacks: PTB-XL test fold, mean over models")
ax.legend(frameon=False, fontsize=9)
ax.spines[["top", "right"]].set_visible(False)
fig.tight_layout()
fig.savefig(ROOT / "study/false_mi.png", dpi=150)
print((ROOT / "study/RESULTS.md").read_text()[:2500])
