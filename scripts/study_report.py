      "outputs of standard deep-learning diagnosis models strongly, and how much at a fixed operating point.",
      "- For the exact interchanges, undoing a correctly identified swap returns the original signal, so the recovery under "
      "detect-and-correct equals LeadCheck's detection and typing accuracy; the independent numbers are the cost on correctly "
